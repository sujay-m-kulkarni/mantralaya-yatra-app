// Writes src/app/core/version.ts: the app version, the commit, the build time, the server the app talks to
// and its sign-in settings. Runs automatically before start, build and test (see package.json).
//
// The server and sign-in settings come from app.config.json, so laptop builds and pipeline releases point at
// the same Azure API. Environment variables override them:
//   MY_API_URL          e.g. http://localhost:5180 to work against the API on this laptop
//   MY_VERSION          set by the release pipeline from the PR's label, e.g. 0.2.0
//   MY_AUTH_AUTHORITY, MY_AUTH_CLIENT_ID, MY_AUTH_SCOPE
//   MY_DEV_SIGNIN=1     no Entra sign-in: the build uses the API's Development header (a laptop API only)
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
// A byte-order mark (added by some Windows editors) is dropped; JSON.parse rejects it.
const config = JSON.parse(readFileSync(join(root, 'app.config.json'), 'utf8').replace(/^\uFEFF/, ''));

const version = process.env.MY_VERSION || pkg.version;
const server = (process.env.MY_API_URL || config.apiUrl || 'http://localhost:5180').replace(/\/+$/, '');
const devSignIn = process.env.MY_DEV_SIGNIN === '1';
const auth = devSignIn
  ? { authority: '', clientId: '', scope: '' }
  : {
      authority: (process.env.MY_AUTH_AUTHORITY || config.auth?.authority || '').replace(/\/+$/, ''),
      clientId: process.env.MY_AUTH_CLIENT_ID || config.auth?.clientId || '',
      scope: process.env.MY_AUTH_SCOPE || config.auth?.scope || '',
    };

if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`The version "${version}" must be three numbers, such as 0.1.0.`);
  process.exit(1);
}
if (!/^https?:\/\/[^\s'"\\]+$/.test(server)) {
  console.error(`The server "${server}" must be an http or https address.`);
  process.exit(1);
}
for (const [key, value] of Object.entries(auth)) {
  if (/['"\\\s]/.test(value)) {
    console.error(`auth.${key} in app.config.json contains a quote, backslash or space.`);
    process.exit(1);
  }
}

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch {
  // Not a git checkout, or git is not installed. The version still works without it.
}

writeFileSync(
  join(root, 'src/app/core/version.ts'),
  `// Generated by scripts/write-version.mjs from package.json and app.config.json. Do not edit.\n` +
    `export const APP_VERSION = '${version}';\n` +
    `export const APP_COMMIT = '${commit}';\n` +
    `export const BUILT_AT = '${new Date().toISOString()}';\n` +
    `/** The API this build talks to. */\n` +
    `export const DEFAULT_SERVER = '${server}';\n` +
    `/** Entra External ID sign-in. Empty authority means this build uses the API's Development header instead. */\n` +
    `export const AUTH_AUTHORITY = '${auth.authority}';\n` +
    `export const AUTH_CLIENT_ID = '${auth.clientId}';\n` +
    `export const AUTH_SCOPE = '${auth.scope}';\n`,
);
console.log(`version.ts: ${version} (${commit}), server ${server}, sign-in ${auth.authority ? 'Entra' : 'dev header'}`);
