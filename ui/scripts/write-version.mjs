// Writes src/app/core/version.ts with the app version, the commit, the build time and the default server.
// Runs automatically before start, build and test (see package.json).
// The release pipeline sets MY_VERSION (e.g. 0.2.0, from the PR's label) and MY_API_URL (the Azure API),
// so an installed app shows its real version and points at the live server without typing.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = process.env.MY_VERSION || JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const server = (process.env.MY_API_URL || 'http://localhost:5180').replace(/\/+$/, '');

if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`The version "${version}" must be three numbers, such as 0.1.0.`);
  process.exit(1);
}

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch {
  // Not a git checkout, or git is not installed. The version still works without it.
}

writeFileSync(
  join(root, 'src/app/core/version.ts'),
  `// Generated by scripts/write-version.mjs. Do not edit; the version comes from package.json.\n` +
    `export const APP_VERSION = '${version}';\n` +
    `export const APP_COMMIT = '${commit}';\n` +
    `export const BUILT_AT = '${new Date().toISOString()}';\n` +
    `/** The server the Set up screen offers; the Azure API in release builds. */\n` +
    `export const DEFAULT_SERVER = '${server}';\n`,
);
console.log(`version.ts: ${version} (${commit}), server ${server}`);
