// Writes src/app/core/version.ts with the app version, the commit and the build time.
// Runs automatically before start, build and test (see package.json).
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;

if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`package.json version "${version}" must be three numbers, such as 0.1.0.`);
  process.exit(1);
}

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch {
  // Not a git checkout, or git is not installed. The version still works without it.
}

writeFileSync(
  join(root, 'src/app/core/version.ts'),
  `// Generated by scripts/write-version.mjs. Do not edit; the version comes from package.json.\n` +
    `export const APP_VERSION = '${version}';\n` +
    `export const APP_COMMIT = '${commit}';\n` +
    `export const BUILT_AT = '${new Date().toISOString()}';\n`,
);
console.log(`version.ts: ${version} (${commit})`);
