// Writes src/app/core/version.ts: the app version, the commit, the build time, the server the app talks to and
// the API key it sends. Runs automatically before start, build and test (see package.json). version.ts is
// git-ignored, because it holds the key.
//
// The server comes from app.config.json, so laptop builds and pipeline releases point at the same Azure API.
// The key comes from app.secrets.json (git-ignored; infra/azure-setup.ps1 writes it) or MY_API_KEY (the release
// pipeline passes the API_KEY GitHub secret). Environment variables:
//   MY_API_URL          e.g. http://localhost:5180 to work against the API on this laptop
//   MY_API_KEY          the API key, over app.secrets.json
//   MY_VERSION          set by the release pipeline from the PR's label, e.g. 0.2.0
//   MY_DEV_SIGNIN=1     no key: the build uses the API's Development header (a laptop API only)
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
// A byte-order mark (added by some Windows editors) is dropped; JSON.parse rejects it.
const config = JSON.parse(readFileSync(join(root, 'app.config.json'), 'utf8').replace(/^\uFEFF/, ''));

const version = process.env.MY_VERSION || pkg.version;
const server = (process.env.MY_API_URL || config.apiUrl || 'http://localhost:5180').replace(/\/+$/, '');
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const secretsFile = join(root, 'app.secrets.json');
const secrets = existsSync(secretsFile) ? readJson(secretsFile) : {};
const devSignIn = process.env.MY_DEV_SIGNIN === '1';
const apiKey = devSignIn ? '' : process.env.MY_API_KEY || secrets.apiKey || '';

if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`The version "${version}" must be three numbers, such as 0.1.0.`);
  process.exit(1);
}
if (!/^https?:\/\/[^\s'"\\]+$/.test(server)) {
  console.error(`The server "${server}" must be an http or https address.`);
  process.exit(1);
}
if (apiKey && !/^[A-Za-z0-9_-]{32,200}$/.test(apiKey)) {
  console.error('The API key must be 32 or more letters, digits, - or _ (app.secrets.json or MY_API_KEY).');
  process.exit(1);
}

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch {
  // Not a git checkout, or git is not installed. The version still works without it.
}

writeFileSync(
  join(root, 'src/app/core/version.ts'),
  `// Generated by scripts/write-version.mjs. Do not edit, do not commit (it holds the API key).\n` +
    `export const APP_VERSION = '${version}';\n` +
    `export const APP_COMMIT = '${commit}';\n` +
    `export const BUILT_AT = '${new Date().toISOString()}';\n` +
    `/** The API this build talks to. */\n` +
    `export const DEFAULT_SERVER = '${server}';\n` +
    `/** Sent as X-Api-Key with every call. Empty: this build uses the API's Development header instead. */\n` +
    `export const API_KEY = '${apiKey}';\n`,
);
console.log(`version.ts: ${version} (${commit}), server ${server}, ${apiKey ? 'API key set' : 'no API key (dev header)'}`);
if (!apiKey && !devSignIn && server.startsWith('https://')) {
  console.warn('WARNING: no API key for an https server. The app will get 401. See docs/guides/android-setup.md, "The API key".');
}
